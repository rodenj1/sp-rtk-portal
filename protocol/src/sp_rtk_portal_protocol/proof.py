"""Request proofs: every agent request is signed with the base key.

A proof is a DPoP-style JWS (RFC 9449) in compact form, sent as
``Authorization: Signature <proof>``:

- header ``{"typ": "dpop+jwt", "alg": "EdDSA", "jwk": <the public key>}``
- claims ``htm`` (method), ``htu`` (URL without query or fragment), ``iat``
  (seconds), ``jti`` (random, single use), ``bh`` (base64url SHA-256 of the
  request body, when there is one) and optionally ``nonce``.

The Portal stores only the public key and finds a base by the key's RFC 7638
thumbprint. No tokens are issued: every request carries a fresh proof.
"""

from __future__ import annotations

import base64
import hashlib
import json
import secrets
from dataclasses import dataclass
from datetime import datetime, timedelta, timezone
from typing import Any
from urllib.parse import urlsplit, urlunsplit

from cryptography.exceptions import InvalidSignature
from cryptography.hazmat.primitives import serialization
from cryptography.hazmat.primitives.asymmetric.ed25519 import (
    Ed25519PrivateKey,
    Ed25519PublicKey,
)

PROOF_TYPE = "dpop+jwt"
ALGORITHM = "EdDSA"
AUTHORIZATION_SCHEME = "Signature"
MAX_CLOCK_SKEW = timedelta(seconds=60)
"""How far a proof's ``iat`` may be from the verifier's clock, either way."""


class ProofError(Exception):
    """A proof that must be refused. The message says why (for logs)."""


def _b64(data: bytes) -> str:
    return base64.urlsafe_b64encode(data).rstrip(b"=").decode("ascii")


def _unb64(text: str) -> bytes:
    if not isinstance(text, str):
        raise ProofError("malformed proof")
    try:
        return base64.urlsafe_b64decode(text + "=" * (-len(text) % 4))
    except (ValueError, TypeError) as exc:
        raise ProofError("malformed proof") from exc


def _json_part(text: str) -> dict[str, Any]:
    try:
        value = json.loads(_unb64(text))
    except ValueError as exc:
        raise ProofError("malformed proof") from exc
    if not isinstance(value, dict):
        raise ProofError("malformed proof")
    return value


def jwk_thumbprint(jwk: dict[str, Any]) -> str:
    """RFC 7638 thumbprint (SHA-256, base64url) of an Ed25519 public JWK."""
    canonical = json.dumps(
        {"crv": jwk["crv"], "kty": jwk["kty"], "x": jwk["x"]},
        separators=(",", ":"),
        sort_keys=True,
    )
    return _b64(hashlib.sha256(canonical.encode()).digest())


def body_hash(body: bytes) -> str:
    return _b64(hashlib.sha256(body).digest())


def request_url(url: str) -> str:
    """The ``htu`` form of a URL: no query, no fragment."""
    parts = urlsplit(url)
    return urlunsplit((parts.scheme, parts.netloc, parts.path, "", ""))


def _public_jwk(key: Ed25519PublicKey) -> dict[str, str]:
    raw = key.public_bytes(serialization.Encoding.Raw, serialization.PublicFormat.Raw)
    return {"kty": "OKP", "crv": "Ed25519", "x": _b64(raw)}


class BaseKey:
    """A base's Ed25519 key, generated by the agent at Claim."""

    def __init__(self, private_key: Ed25519PrivateKey) -> None:
        self._key = private_key
        self.public_jwk = _public_jwk(private_key.public_key())
        self.thumbprint = jwk_thumbprint(self.public_jwk)

    @classmethod
    def generate(cls) -> BaseKey:
        return cls(Ed25519PrivateKey.generate())

    @classmethod
    def from_pem(cls, data: bytes) -> BaseKey:
        key = serialization.load_pem_private_key(data, password=None)
        if not isinstance(key, Ed25519PrivateKey):
            raise ValueError("not an Ed25519 key")
        return cls(key)

    def to_pem(self) -> bytes:
        """PKCS#8 PEM, unencrypted (the file's mode protects it)."""
        return self._key.private_bytes(
            serialization.Encoding.PEM,
            serialization.PrivateFormat.PKCS8,
            serialization.NoEncryption(),
        )

    def sign(self, data: bytes) -> bytes:
        """A raw Ed25519 signature of ``data`` (a Doorbell keepalive's)."""
        return self._key.sign(data)

    def proof(
        self,
        method: str,
        url: str,
        *,
        now: datetime,
        body: bytes | None = None,
        nonce: str | None = None,
    ) -> str:
        header = {"typ": PROOF_TYPE, "alg": ALGORITHM, "jwk": self.public_jwk}
        claims: dict[str, Any] = {
            "htm": method.upper(),
            "htu": request_url(url),
            "iat": int(now.timestamp()),
            "jti": secrets.token_urlsafe(16),
        }
        if body:
            claims["bh"] = body_hash(body)
        if nonce is not None:
            claims["nonce"] = nonce
        signing_input = (
            _b64(json.dumps(header, separators=(",", ":")).encode())
            + "."
            + _b64(json.dumps(claims, separators=(",", ":")).encode())
        )
        signature = self._key.sign(signing_input.encode("ascii"))
        return signing_input + "." + _b64(signature)

    def authorization(
        self,
        method: str,
        url: str,
        *,
        now: datetime,
        body: bytes | None = None,
        nonce: str | None = None,
    ) -> str:
        """The ``Authorization`` header value for one request."""
        proof = self.proof(method, url, now=now, body=body, nonce=nonce)
        return f"{AUTHORIZATION_SCHEME} {proof}"


@dataclass(frozen=True)
class VerifiedProof:
    thumbprint: str
    jwk: dict[str, str]
    jti: str
    issued_at: datetime
    nonce: str | None


def proof_from_authorization(header: str | None) -> str:
    """The proof in an ``Authorization: Signature <proof>`` header."""
    scheme, _, proof = (header or "").partition(" ")
    if scheme != AUTHORIZATION_SCHEME or not proof.strip():
        raise ProofError("no signed proof")
    return proof.strip()


def verify_proof(
    proof: str,
    *,
    method: str,
    url: str,
    now: datetime,
    body: bytes | None = None,
    max_skew: timedelta = MAX_CLOCK_SKEW,
) -> VerifiedProof:
    """Check ``proof`` was made for this request, now, by the key it names.

    Raises :class:`ProofError`. Replays are the verifier's to catch: pass the
    result to a :class:`ReplayCache`.
    """
    parts = proof.split(".")
    if len(parts) != 3:
        raise ProofError("malformed proof")
    header, claims = _json_part(parts[0]), _json_part(parts[1])
    signature = _unb64(parts[2])
    if header.get("typ") != PROOF_TYPE or header.get("alg") != ALGORITHM:
        raise ProofError("wrong proof type or algorithm")
    jwk = header.get("jwk")
    if (
        not isinstance(jwk, dict)
        or jwk.get("kty") != "OKP"
        or jwk.get("crv") != "Ed25519"
        or not isinstance(jwk.get("x"), str)
        or set(jwk) - {"kty", "crv", "x"}
    ):
        raise ProofError("not an Ed25519 public key")
    try:
        public = Ed25519PublicKey.from_public_bytes(_unb64(jwk["x"]))
        public.verify(signature, f"{parts[0]}.{parts[1]}".encode("ascii"))
    except (InvalidSignature, ValueError) as exc:
        raise ProofError("bad signature") from exc

    if claims.get("htm") != method.upper() or claims.get("htu") != request_url(url):
        raise ProofError("proof made for another request")
    iat, jti = claims.get("iat"), claims.get("jti")
    if not isinstance(iat, int) or isinstance(iat, bool):
        raise ProofError("proof has no time")
    if not isinstance(jti, str) or not jti:
        raise ProofError("proof has no jti")
    issued = datetime.fromtimestamp(iat, tz=timezone.utc)
    if abs(now - issued) > max_skew:
        raise ProofError("proof time is too far from now")
    if body and claims.get("bh") != body_hash(body):
        raise ProofError("proof doesn't match the body")
    nonce = claims.get("nonce")
    return VerifiedProof(
        thumbprint=jwk_thumbprint(jwk),
        jwk={"kty": "OKP", "crv": "Ed25519", "x": jwk["x"]},
        jti=jti,
        issued_at=issued,
        nonce=nonce if isinstance(nonce, str) else None,
    )


class ReplayCache:
    """Remembers each proof's ``jti`` for as long as the proof could verify.

    In memory: the Portal is a single instance (ADR 0002 / #70).
    """

    def __init__(self, max_skew: timedelta = MAX_CLOCK_SKEW) -> None:
        self._window = max_skew
        self._seen: dict[tuple[str, str], datetime] = {}

    def __len__(self) -> int:
        return len(self._seen)

    def remember(self, proof: VerifiedProof, *, now: datetime) -> None:
        """Record ``proof``; raise :class:`ProofError` if it was seen before."""
        self._seen = {k: until for k, until in self._seen.items() if until >= now}
        key = (proof.thumbprint, proof.jti)
        if key in self._seen:
            raise ProofError("replayed proof")
        self._seen[key] = proof.issued_at + self._window
